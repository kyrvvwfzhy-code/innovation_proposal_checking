def ocr_result(number, date, name, author):
    text = (f"Рационализаторское предложение зарегестрировано под номером {number}\n\n"
            
            f"Дата регистрации: {date}\n\n"

            f"Наименование: {name}\n\n"

            f"Автор: {author}\n\n"
    )
    return text
         
def base_prompt_text(new_name, best_name, max_similarity):
    text = f"""Задача: Проверить уникальность рационализаторского предложения.

        Входные данные:
        - Новое предложение: "{new_name}"
        - Существующее: "{best_name}"  
        - Семантическое сходство: {max_similarity:.2f}

        Критерии похожести:
        - 0.00-0.30: разные темы → ДОБАВИТЬ
        - 0.30-0.60: частично похожи → проанализировать различия
        - 0.60-0.80: очень похожи → вероятно НЕ ДОБАВЛЯТЬ  
        - 0.80-1.00: почти идентичны → НЕ ДОБАВЛЯТЬ

        Формат ответа (4 строки):
        [1] "{new_name}" vs "{best_name}"
        [2] Отличия: <краткий анализ (1 ыпредложение)>
        [3] Общее сходство: <X>%
        [4] Решение: <ДОБАВИТЬ/НЕ ДОБАВЛЯТЬ> - <причина (1 предложение)>"""
    return text